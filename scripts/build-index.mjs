#!/usr/bin/env node
// Regenerates diagrams.json and index.html from the HTML files in diagrams/.
//
// Layout: diagrams/<anything containing YYYY-MM-DD or YYYYMMDD>.html
// Every diagram is a self-contained page; this only reads the bits needed to
// list it. index.html is a plain redirect to the newest diagram, so the site
// root always opens on the current week. Run `npm run index` after adding files.

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'diagrams');

const strip = (s) => s.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();
const first = (html, re) => {
  const m = html.match(re);
  return m ? strip(m[1]) : '';
};
const meta = (html, name) =>
  first(html, new RegExp(`<meta[^>]*name="diagram:${name}"[^>]*content="([^"]*)"`, 'i'));
const fileDate = (name) => {
  const m = name.match(/(\d{4})-?(\d{2})-?(\d{2})/);
  return m ? `${m[1]}-${m[2]}-${m[3]}` : '';
};

const diagrams = [];
const seen = new Set();
for (const file of (await readdir(dir)).filter((f) => f.endsWith('.html')).sort()) {
  const html = await readFile(join(dir, file), 'utf8');
  const date = meta(html, 'date') || fileDate(file);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) {
    console.warn(`skipping diagrams/${file}: no YYYY-MM-DD in the filename or diagram:date meta`);
    continue;
  }
  if (seen.has(date)) {
    console.warn(`skipping diagrams/${file}: a ${date} diagram is already indexed`);
    continue;
  }
  seen.add(date);
  diagrams.push({
    date,
    path: `diagrams/${file}`,
    title: first(html, /<title>([\s\S]*?)<\/title>/i),
    heading: first(html, /<h1[^>]*>([\s\S]*?)<\/h1>/i),
  });
}
diagrams.sort((a, b) => (a.date < b.date ? 1 : -1));

if (!diagrams.length) {
  console.error('no diagrams found in diagrams/; index.html left unchanged');
  process.exit(1);
}

const latest = diagrams[0];
await writeFile(
  join(root, 'diagrams.json'),
  JSON.stringify({ generated: new Date().toISOString(), latest: latest.path, diagrams }, null, 2) + '\n',
);
await writeFile(
  join(root, 'index.html'),
  `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<!-- Generated by scripts/build-index.mjs. Redirects to the newest diagram. -->
<title>Weekly Flow Diagram</title>
<link rel="icon" href="favicon.svg" type="image/svg+xml">
<meta http-equiv="refresh" content="0; url=${latest.path}">
<link rel="canonical" href="${latest.path}">
</head>
<body>
<p>Opening <a href="${latest.path}">${latest.title || latest.date}</a>…</p>
</body>
</html>
`,
);

console.log(`diagrams.json: ${diagrams.length} diagram(s); index.html -> ${latest.path}`);
